export const MESSAGES: Record<AppLocale, Record<MessageKey, string>> = {
  id: ID_MESSAGES,
  en: EN_MESSAGES,
};

/** Normalisasi nilai apa pun menjadi locale yang didukung (fallback `id`). */
export function resolveLocale(value: unknown): AppLocale {
  return typeof value === 'string' && (SUPPORTED_LOCALES as readonly string[]).includes(value)
    ? (value as AppLocale)
    : DEFAULT_LOCALE;
}

/** Terjemahkan `key` untuk `locale`, ganti `{nama}` dengan `vars`; fallback ke `id`, lalu key. */
export function translate(
  locale: unknown,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  const active = resolveLocale(locale);
  let out = MESSAGES[active][key] ?? MESSAGES[DEFAULT_LOCALE][key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      out = out.replaceAll(`{${name}}`, String(value));
    }
  }
  return out;
}

/** True bila kedua kamus memuat himpunan kunci yang sama (penjaga kelengkapan). */
export function catalogsComplete(): boolean {
  const idKeys = Object.keys(MESSAGES.id).sort();
  const enKeys = Object.keys(MESSAGES.en).sort();
  return idKeys.length === enKeys.length && idKeys.every((k, i) => k === enKeys[i]);
}
